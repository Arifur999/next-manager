// Every query key in the app comes from here. Each domain keeps the root string
// it had as an inline literal, so `.all` still prefix-matches any key written
// the old way while the codebase migrates.
export const createDomainKeys = <TRoot extends string>(root: TRoot) => ({
  all: [root] as const,
  list: (queryString = "") => [root, "list", queryString] as const,
  count: (queryString = "") => [root, "count", queryString] as const,
  detail: (id: string) => [root, "detail", id] as const,
})

